#!/usr/bin/env python3
"""Build step: mark «Спец инвойс» (invoice: true) on every STOCK car listed in spec-invoice.json.

Called at the end of patch_issue.py (last build step in pages.yml, after patch_stock_src.py /
patch_fleet_dcti.py), so it also covers
TENET+ cars and T9 (patch_stock_src sets invoice False on all EDEHD24).
spec-invoice.json holds VINs only (generated by scripts/spec_invoice.py from Logicstars CSV),
so the purchase cost never reaches the site. Only adds the flag; NOT_INVOICE VINs stay unflagged.
"""
import json, re, shutil, subprocess, tempfile
from pathlib import Path

STOCK_RE = re.compile(r"(const STOCK = )(\[.*?\])(;)", re.S)
NOT_INVOICE = {"EDXGD34B7TE034443"}


def load_vins():
    p = Path("spec-invoice.json")
    if not p.exists():
        return set()
    d = json.loads(p.read_text(encoding="utf-8"))
    return {str(v).strip().upper() for v in d.get("vins") or [] if str(v).strip()} - NOT_INVOICE


def js_ok(html):
    node = shutil.which("node")
    if not node:
        return True
    for i, m in enumerate(re.finditer(r"<script(?![^>]*\bsrc=)[^>]*>(.*?)</script>", html, re.S)):
        if "const STOCK" not in m.group(1):
            continue
        with tempfile.NamedTemporaryFile("w", suffix=".js", delete=False, encoding="utf-8") as f:
            f.write(m.group(1))
        r = subprocess.run([node, "--check", f.name], capture_output=True, text=True)
        Path(f.name).unlink(missing_ok=True)
        if r.returncode:
            print("spec-invoice: node --check failed:", r.stderr[:400])
            return False
    return True


def patch(path, vins):
    p = Path(path)
    if not p.exists():
        return
    html = p.read_text(encoding="utf-8")
    m = STOCK_RE.search(html)
    if not m:
        print(f"spec-invoice: {path}: STOCK not found")
        return
    try:
        cars = json.loads(m.group(2))
    except Exception as e:
        print(f"spec-invoice: {path}: STOCK is not JSON ({e}), skipped")
        return
    added = 0
    for c in cars:
        if isinstance(c, dict) and str(c.get("vin", "")).upper() in vins and c.get("invoice") is not True:
            c["invoice"] = True
            added += 1
    total = sum(1 for c in cars if isinstance(c, dict) and c.get("invoice") is True)
    if added:
        new = html[: m.start(2)] + json.dumps(cars, ensure_ascii=False) + html[m.end(2):]
        if not js_ok(new):
            print(f"spec-invoice: {path}: JS check failed, file left unchanged")
            return
        p.write_text(new, encoding="utf-8")
    print(f"spec-invoice: {path}: +{added}, invoice total {total} of {len(cars)}")


def main():
    vins = load_vins()
    print(f"spec-invoice: {len(vins)} VINs in spec-invoice.json")
    if vins:
        for f in ("index.html", "_site/index.html"):
            patch(f, vins)


if __name__ == "__main__":
    main()
